const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const listeners = {};
const context = { window: { StarCatch: { $: () => ({}) }, addEventListener: (name, fn) => listeners[name] = fn }, document: { addEventListener() {} } };
vm.createContext(context);
for (const name of ['scoring', 'spawning', 'controls']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../js', name + '.js'), 'utf8'), context);
const api = context.window.StarCatch;
assert.equal(api.resolveCatch('fruit', 1).points, 10);
assert.equal(api.resolveCatch('fruit', 2).points, 20);
assert.equal(api.resolveCatch('star', 4).points, 80);
assert.equal(api.resolveCatch('bomb', 3).combo, 0);
const source = { x: 450, y: 400 };
const items = [{x:450,y:200,kind:'fruit',icon:'🍎'}, {x:500,y:200,kind:'bomb',icon:'💣'}, {x:100,y:200,kind:'fruit',icon:'🍐'}];
api.activateMiniStar(items, source, 1);
assert.equal(items[0].kind, 'star');
assert.equal(items[1].kind, 'star');
assert.equal(items[2].kind, 'fruit');
api.restoreMiniStars(items, 3.99);
assert.equal(items[1].kind, 'star');
api.restoreMiniStars(items, 4);
assert.equal(items[0].kind, 'fruit');
assert.equal(items[0].icon, '🍎');
assert.equal(items[1].kind, 'bomb');
assert.equal(items[1].icon, '💣');
for (const [roll, kind] of [[.981,'star'], [.982,'superstar'], [.999,'superstar'], [.90,'ministar']]) {
  assert.equal(api.createDrop({bomb:.1,star:.3,speed:120,accel:2,interval:.5},0,()=>roll).items[0].kind, kind);
}
const keys = {};
api.bindControls({canvas:{}, keys, getState:()=> 'ready', start(){}, togglePause(){}, moveBasket(){}});
listeners.keydown({key:'B',preventDefault(){}});
assert.equal(keys.turbo,true);
listeners.keyup({key:'B'});
assert.equal(keys.turbo,false);
listeners.keydown({key:'b',preventDefault(){}});
listeners.blur();
assert.equal(keys.turbo,false);
console.log('PASS: 3-combo fever, item probabilities, mini-star range and 3-second fruit/bomb restoration, B hold/release and blur reset');
